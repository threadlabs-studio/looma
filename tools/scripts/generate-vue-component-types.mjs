import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../..");
const eventTypes = {
  open: "VueAdapterEventMap['open']",
  close: "VueAdapterEventMap['close']",
  select: "VueAdapterEventMap['select']",
  change: "VueAdapterEventMap['change']",
  input: "VueAdapterEventMap['input']",
  dismiss: "VueAdapterEventMap['dismiss']",
  reorder: "VueAdapterEventMap['reorder']",
  "reorder-rejected": "VueAdapterEventMap['reorderRejected']",
  expand: "VueAdapterEventMap['expand']",
};

const callbackName = (event) => `on${event.replace(/(^|-)([a-z])/g, (_, __, character) => character.toUpperCase())}`;

export async function generateVueComponentTypes() {
  const api = JSON.parse(await readFile(path.join(repoRoot, "generated/component-api.json"), "utf8"));
  const source = await readFile(path.join(repoRoot, "packages/vue/src/index.ts"), "utf8");
  const mapMatch = source.match(/export const ADAPTER_COMPONENT_TAG_MAP = \{([\s\S]*?)\} as const;/);
  if (!mapMatch) throw new Error("Could not find ADAPTER_COMPONENT_TAG_MAP");
  const componentMap = [...mapMatch[1].matchAll(/([A-Za-z0-9_]+): "(ui-[a-z0-9-]+)"/g)]
    .map(([, name, tag]) => ({ name, tag }))
    // Combobox is already an explicit Vue component with richer v-model and slot types.
    .filter(({ name }) => name !== "Combobox");
  const byTag = new Map(api.components.map((component) => [component.tag, component]));

  const lines = [
  "// This file is generated by tools/scripts/generate-vue-component-types.mjs. Do not edit manually.",
  "import type { VueAdapterEventMap } from './adapter';",
  "",
  "export interface AdapterBaseProps {",
  "  'data-allow-mismatch'?: string;",
  "}",
  "",
  ];

  for (const { name, tag } of componentMap) {
  const component = byTag.get(tag);
  if (!component) throw new Error(`No API metadata found for ${tag}`);
  lines.push(`export interface ${name}Props extends AdapterBaseProps {`);
  for (const property of component.properties ?? []) {
    lines.push(`  ${JSON.stringify(property.name)}?: ${property.type ?? "unknown"} | undefined;`);
  }
  for (const event of component.events ?? []) {
    const type = eventTypes[event.name];
    if (type) lines.push(`  ${JSON.stringify(callbackName(event.name))}?: ((detail: ${type}) => void) | undefined;`);
  }
  lines.push("}", "");
  }

  lines.push("export interface AdapterComponentProps {");
  for (const { name } of componentMap) lines.push(`  ${JSON.stringify(name)}: ${name}Props;`);
  lines.push("}", "");

  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}

async function main() {
  await writeFile(
    path.join(repoRoot, "packages/vue/src/generated-component-types.ts"),
    await generateVueComponentTypes(),
    "utf8",
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.stack : String(error)}\n`);
    process.exitCode = 1;
  });
}
