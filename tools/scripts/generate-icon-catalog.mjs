// Writes packages/looma/src/components/shared/icons.js: Looma's icon set (LOOMA_ICONS, which imports
// Lucide) serialized to plain data, so controllers can import it straight into a browser without a
// bundler. Run after adding an icon to editor/icons.ts; icon-catalog-rule.test.mjs holds the two equal.
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const { LOOMA_ICONS } = await import(path.join(repoRoot, "packages/looma/src/editor/icons.ts"));

const entries = Object.keys(LOOMA_ICONS).sort().map((name) => {
  const nodes = LOOMA_ICONS[name].map(([tag, attributes]) => [tag, Object.fromEntries(Object.entries(attributes).filter(([key]) => key !== "key"))]);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(nodes)},`;
});
const source = `// Generated by tools/scripts/generate-icon-catalog.mjs from LOOMA_ICONS. Do not edit.
export const icons = {
${entries.join("\n")}
};
`;
await writeFile(path.join(repoRoot, "packages/looma/src/components/shared/icons.js"), source);
console.log(`Wrote ${entries.length} icons.`);
