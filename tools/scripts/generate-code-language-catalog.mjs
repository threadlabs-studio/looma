import { readdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const require = createRequire(resolve(root, "packages/looma/package.json"));
const languageDirectory = dirname(require.resolve("highlight.js/lib/languages/bash"));
const grammars = (await readdir(languageDirectory))
  .filter((name) => name.endsWith(".js") && !name.endsWith(".js.js"))
  .map((name) => name.slice(0, -3))
  .sort();
const names = [...new Set([...grammars, "html"])].sort();
const autoLanguages = [
  "bash", "c", "cpp", "csharp", "css", "go", "html", "java", "javascript", "json",
  "kotlin", "markdown", "php", "python", "ruby", "rust", "sql", "swift", "typescript", "yaml",
];

const source = [
  "// Generated by tools/scripts/generate-code-language-catalog.mjs from the installed Highlight.js grammars.",
  "// Static imports let bundlers split every manual choice into a separate chunk.",
  "export const codeLanguageCatalog = {",
  ...names.map((name) => `  ${JSON.stringify(name)}: () => import("highlight.js/lib/languages/${name === "html" ? "xml" : name}").then((module) => module.default),`),
  "} as const;",
  "",
  "// Auto detection stays bounded even though the manual picker includes every grammar.",
  "export const autoCodeLanguageNames = [",
  ...autoLanguages.map((name) => `  ${JSON.stringify(name)},`),
  "] as const satisfies readonly (keyof typeof codeLanguageCatalog)[];",
  "",
].join("\n");
await writeFile(resolve(root, "packages/looma/src/vue/editor/code-language-catalog.ts"), source);
